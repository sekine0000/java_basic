package chapter_09.practice.ques_06;

class ReadingProgressAi {
    public static void main(String[] args) {
        int pagesRead = 280;

        if (pagesRead >= 300) {
            System.out.println("300ページ以上読み終わりました。");
        } else {
            System.out.println("読み終わったページ数は300ページ未満です。");
        }
    }
}
